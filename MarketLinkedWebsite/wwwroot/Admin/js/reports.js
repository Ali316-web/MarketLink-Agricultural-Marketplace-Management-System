/* Reports section */
(function(){
"use strict";
const {db,st,esc,money,badge,empty,marketName,farmerName,mapLink}=ML;
ML.mount(()=>{
  const totalOrders=db.farmers.reduce((s,f)=>s+f.orders,0);
  const totalRev=db.farmers.reduce((s,f)=>s+f.revenue,0);
  const byMarket=db.markets.map(m=>({name:m.name,rev:db.farmers.filter(f=>f.market===m.id).reduce((s,f)=>s+f.revenue,0),ord:db.farmers.filter(f=>f.market===m.id).reduce((s,f)=>s+f.orders,0)})).sort((a,b)=>b.rev-a.rev);
  const maxRev=Math.max(1,...byMarket.map(x=>x.rev));
  const top=db.farmers.slice().sort((a,b)=>b.orders-a.orders).slice(0,5);
  return `
  <div class="page-head"><div><h1>Reports and analytics</h1><p>Platform-wide totals across all markets.</p></div>
  <button class="btn primary" data-a="rep-new">Generate report</button></div>
  <div class="stats" style="grid-template-columns:repeat(3,1fr)">
    <div class="stat"><div class="n">${totalOrders.toLocaleString()}</div><div class="l">Total orders</div></div>
    <div class="stat"><div class="n">${money(totalRev)}</div><div class="l">Total revenue</div></div>
    <div class="stat"><div class="n">${totalOrders?money(totalRev/totalOrders):"$0"}</div><div class="l">Average order value</div></div>
  </div>
  <div class="grid2">
    <div class="panel"><h2>Revenue by market</h2>
      ${byMarket.map(x=>`<div class="bar-row"><span>${esc(x.name)}</span><div class="bar"><i style="width:${Math.round(x.rev/maxRev*100)}%"></i></div><span style="text-align:right">${money(x.rev)}</span></div>`).join("")}
    </div>
    <div class="panel"><h2>Most active farmers</h2>
      <ul class="list">${top.map(f=>`<li><div class="t"><b>${esc(f.stall)}</b><div class="muted small">${esc(marketName(f.market))}</div></div><span>${f.orders} orders</span></li>`).join("")}</ul>
    </div>
  </div>
  <div class="panel"><h2>Generated reports</h2>
    <div class="tablewrap"><table><thead><tr><th>ID</th><th>Report type</th><th>Generated by</th><th>Generated at</th></tr></thead><tbody>
    ${db.reports.slice().reverse().map(r=>`<tr><td>#${r.id}</td><td>${esc(r.type)}</td><td>${esc(r.by)}</td><td>${esc(r.at)}</td></tr>`).join("")}
    </tbody></table></div>
  </div>`;
});
})();
